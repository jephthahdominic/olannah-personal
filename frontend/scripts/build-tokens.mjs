// Generates tokens/tokens.generated.css and tokens/tokens.generated.ts from tokens/tokens.json.
// Pixel values are authored in px (BRD 1.3) and emitted in rem so OS text scaling and 200% zoom work.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'));
const rem = (px) => (px === 0 ? '0' : `${+(px / 16).toFixed(4)}rem`);

const names = [];
const lines = [];
const decl = (name, value) => {
  names.push(name);
  lines.push(`  --${name}: ${value};`);
};

for (const [n, v] of Object.entries(t.color)) decl(n, v);
for (const [n, v] of Object.entries(t.space)) decl(n, rem(v));
for (const [n, v] of Object.entries(t.width)) decl(n, rem(v));
for (const [n, v] of Object.entries(t.radius)) decl(n, v === 999 ? '999px' : rem(v));
for (const [n, v] of Object.entries(t.icon)) decl(n, rem(v));
for (const [n, v] of Object.entries(t.z)) decl(n, String(v));
for (const [n, v] of Object.entries(t.font)) decl(n, v);
for (const [n, v] of Object.entries(t.motion)) decl(n, v);
for (const [n, v] of Object.entries(t.type)) {
  decl(`${n}-size`, rem(v.size));
  decl(`${n}-line-height`, rem(v.line));
  decl(`${n}-weight`, String(v.weight));
  decl(`${n}-family`, `var(--font-family-${v.family})`);
  if (v.tracking) decl(`${n}-tracking`, v.tracking);
}

// Reserved dark-mode mirrors (1.3 section 3.6): names exist from day one, values intentionally undefined.
const dark = Object.keys(t.color).map((n) => {
  const name = `dark-${n}`;
  names.push(name);
  return `  --${name}: initial;`;
});

const typeClasses = Object.entries(t.type)
  .map(([n, v]) => {
    const extra = v.uppercase ? `\n  text-transform: uppercase;\n  letter-spacing: var(--${n}-tracking);` : '';
    return `.${n} {\n  font-family: var(--${n}-family);\n  font-size: var(--${n}-size);\n  line-height: var(--${n}-line-height);\n  font-weight: var(--${n}-weight);${extra}\n}`;
  })
  .join('\n');

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */
:root {
${lines.join('\n')}

  /* Reserved dark-mode mirrors. Values are intentionally undefined until dark mode (P2). */
${dark.join('\n')}
}

/* Type utility classes: one per type token, so components never mix size, weight and family ad hoc. */
${typeClasses}
`;
writeFileSync(join(root, 'tokens/tokens.generated.css'), css);

const ts = `// GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand.
export const TOKEN_NAMES = ${JSON.stringify(names, null, 2)} as const;
export type TokenName = (typeof TOKEN_NAMES)[number];

export const BREAKPOINTS = {
  mobileMax: ${t.breakpoints['mobile-max']},
  tabletMin: ${t.breakpoints['tablet-min']},
  tabletMax: ${t.breakpoints['tablet-max']},
  desktopMin: ${t.breakpoints['desktop-min']},
} as const;

export type Viewport = 'mobile' | 'tablet' | 'desktop';
`;
writeFileSync(join(root, 'tokens/tokens.generated.ts'), ts);
console.log(`tokens: wrote ${names.length} custom properties`);
