"""The seam between Olannah and the real systems. The mock implements it today; real clients later.

Every method returns the system's RAW data (dicts / rows), exactly as that system would, or None
when the record does not exist. Anything that makes the system unreachable raises
SourceUnavailable. Normalisation happens in app/adapters, never here.
"""
from typing import Any, Optional, Protocol


class SourceUnavailable(Exception):
    """The system is down, timed out, or returned something that is not data."""


class Sources(Protocol):
    # Sampro: system of record
    async def work_order(self, wo_no: int) -> Optional[dict]: ...
    async def tech(self, tech_id: str) -> Optional[dict]: ...
    async def customer(self, cust_id: str) -> Optional[dict]: ...
    async def site(self, site_id: str) -> Optional[dict]: ...
    async def equipment(self, eq_id: str) -> Optional[dict]: ...
    async def service_history(self, eq_id: str) -> list[dict]: ...
    async def van_inventory(self, van_id: str) -> list[dict]: ...
    async def parts(self) -> list[dict]: ...
    async def part_usage(self, part_id: str) -> list[dict]: ...
    # Xtreme
    async def xtreme_work_order(self, external_ref: str) -> Optional[dict]: ...
    # XOi
    async def xoi_workflows(self) -> list[dict]: ...
    # SiteDocs
    async def sitedocs_required(self) -> list[dict]: ...
    async def sitedocs_certs(self, worker_id: str) -> list[dict]: ...
    # Shared drive
    async def drive_history(self) -> list[dict]: ...
    # Client portal (may return a str when it serves a login page instead of data)
    async def portal_ticket(self, po: str) -> Any: ...
